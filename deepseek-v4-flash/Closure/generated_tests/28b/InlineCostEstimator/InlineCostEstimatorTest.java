package com.google.javascript.jscomp;

import static org.junit.Assert.*;

import com.google.javascript.rhino.Node;
import com.google.javascript.jscomp.Compiler;
import com.google.javascript.jscomp.CompilerOptions;

import org.junit.Test;
import org.junit.Before;

/**
 * JUnit 4 test class for InlineCostEstimator.
 * Tests the getCost and getCost with threshold methods
 * using various Node structures.
 */
public class InlineCostEstimatorTest {

  private Compiler compiler;
  private CompilerOptions options;

  @Before
  public void setUp() {
    compiler = new Compiler();
    options = new CompilerOptions();
    // No special setup needed for these tests
  }

  // Helper to parse a JS string into a root Node
  private Node parse(String js) {
    return compiler.parse(js, "test");
  }

  // Test basic cost estimation for a simple expression: 1+2 (3 tokens: 1, +, 2)
  // Expected cost: 3 + identifier costs (of which there are none in literal math)
  @Test
  public void testGetCost_simpleExpression_returnsCorrectCost() {
    Node root = parse("1+2");
    int cost = InlineCostEstimator.getCost(root);
    // The cost should be around 3 (for characters "1", "+", "2")
    // but note: the parser may add semicolons, etc. The estimator
    // processes the AST, so the cost is based on the code generated by CodeGenerator.
    // For "1+2", CodeGenerator will generate "1+2" (3 chars) + maybe a semicolon.
    // A typical cost might be 3 or 4. Let's test for reasonableness.
    // Let's check that cost > 0 and not too large.
    assertEquals(3, cost); // After analysis, it's exactly "1+2"
  }

  // Test cost with threshold (low threshold) to stop processing early
  @Test
  public void testGetCost_withLowThreshold_returnsThresholdExceededCost() {
    Node root = parse("var x = 1; var y = 2; var z = 3;");
    int cost = InlineCostEstimator.getCost(root, 5);
    // With threshold 5, the cost will be at least 5 (stop at or above threshold)
    // The first token "var" is 3 chars, then space is ignored (white space stripped)
    // but CodeGenerator doesn't add whitespace. So "var" is cost 3, next token "x" is "ab" (2 chars) = 5, stops.
    assertTrue("Cost should be at least 5", cost >= 5);
    // But could be slightly more because of semicolon? Actually semicolon is added.
    // "var" = 3, "x" identifier -> "ab" = 2, then "=" = 1, that's 6.
    // The threshold check is after append, so cost becomes 6 > 5 and stops.
    // So cost should be exactly 6.
    assertEquals(6, cost);
  }

  // Test cost for a function declaration
  @Test
  public void testGetCost_functionDeclaration_returnsCorrectCost() {
    Node root = parse("function f() { return 1; }");
    int cost = InlineCostEstimator.getCost(root);
    // "function" (8) + "ab" (2) + "(" (1) + ")" (1) + "{" (1) + "return" (6) + " " + "1" (1) + ";" (1) + "}" (1)
    // = 8 + 2 + 1 + 1 + 1 + 6 + 1 + 1 + 1 = 22. Without space: 8+2+1+1+1+6+1+1+1 = 22
    // Actually CodeGenerator adds semicolons and such. Let's just verify it's positive and finite.
    assertTrue("Cost should be positive", cost > 0);
    // A more precise check: function declaration cost is fairly predictable.
    assertEquals(22, cost); 
  }

  // Test cost for a call expression
  @Test
  public void testGetCost_callExpression_returnsCorrectCost() {
    Node root = parse("alert(1)");
    int cost = InlineCostEstimator.getCost(root);
    // "ab" (2) + "(" (1) + "1" (1) + ")" (1) = 5
    assertEquals(5, cost);
  }

  // Test cost for a simple assignment
  @Test
  public void testGetCost_simpleAssignment_returnsCorrectCost() {
    Node root = parse("x = 1");
    int cost = InlineCostEstimator.getCost(root);
    // "ab" (2) + " " + "=" (1) + " " + "1" (1) --> CodeGenerator: identifier = "ab", "=", "1" => 2+1+1 = 4
    // Semikolon may be added: 4+1 = 5
    // Let's check: Actually "x = 1" becomes "ab=1" in generated code? No, there's an = sign, so "ab=1" = 4 chars.
    // Semikolon is automatically added by CodeGenerator when the statement ends.
    // So final cost = 5.
    assertEquals(5, cost);
  }

  // Test for infinite threshold (large threshold) processes full code
  @Test
  public void testGetCost_largeThreshold_returnsTotalCost() {
    Node root = parse("a + b");
    int cost = InlineCostEstimator.getCost(root, 1000);
    // "ab" (2) + " " + "+" (1) + " " + "ab" (2) = 2+1+2 = 5
    assertEquals(5, cost);
  }

  // Test cost for a number: 12345678901234567890 (big integer)
  @Test
  public void testGetCost_bigInteger_returnsCorrectCost() {
    Node root = parse("12345678901234567890");
    int cost = InlineCostEstimator.getCost(root);
    // The number is processed as a string literal of its digits.
    // CodeGenerator outputs the number as-is.
    assertEquals(20, cost);
  }

  // Test cost for a string literal
  @Test
  public void testGetCost_stringLiteral_returnsCorrectCost() {
    Node root = parse("'hello'");
    int cost = InlineCostEstimator.getCost(root);
    // String includes quotes: 7 characters
    assertEquals(7, cost);
  }

  // Test cost for an empty program
  @Test
  public void testGetCost_emptyProgram_returnsZero() {
    Node root = parse("");
    int cost = InlineCostEstimator.getCost(root);
    // An empty program may have no AST, or a single BLOCK with no children.
    // CodeGenerator will output nothing.
    assertEquals(0, cost);
  }

  // Test threshold with value 0 (minimum cost threshold)
  @Test
  public void testGetCost_zeroThreshold_stopsImmediately() {
    Node root = parse("a");
    int cost = InlineCostEstimator.getCost(root, 0);
    // First append adds 2 (identifier), then cost = 2 >= 0, stop.
    // cost is 2.
    assertTrue(cost >= 0);
    assertEquals(2, cost);
  }

  // Test threshold with value 1 (just enough for one character)
  @Test
  public void testGetCost_thresholdOne_stopsAfterFirstToken() {
    Node root = parse("a");
    int cost = InlineCostEstimator.getCost(root, 1);
    // First append adds 2 (identifier) -> cost=2 >= 1, stop.
    assertEquals(2, cost);
  }

  // Test that identifier is estimated as 2 characters
  @Test
  public void testGetCost_identifier_estimatedAsTwoChars() {
    Node root = parse("a");
    int cost = InlineCostEstimator.getCost(root);
    assertEquals(2, cost);
  }

  // Test cost for expression with many operators
  @Test
  public void testGetCost_expressionWithOperators_returnsCorrectCost() {
    Node root = parse("1 + 2 - 3 * 4 / 5 % 6");
    // CodeGenerator produces: "1+2-3*4/5%6" (11 chars)
    int cost = InlineCostEstimator.getCost(root);
    assertEquals(11, cost);
  }

  // Test cost for a comparison
  @Test
  public void testGetCost_comparison_returnsCorrectCost() {
    Node root = parse("a === b");
    int cost = InlineCostEstimator.getCost(root);
    // "ab" + "===" + "ab" = 2 + 3 + 2 = 7
    assertEquals(7, cost);
  }

  // Test that getCost with default threshold equals getCost with large threshold
  @Test
  public void testGetCost_defaultThresholdEqualsLargeThreshold() {
    Node root = parse("var x = 1;");
    int cost1 = InlineCostEstimator.getCost(root);
    int cost2 = InlineCostEstimator.getCost(root, Integer.MAX_VALUE);
    assertEquals(cost1, cost2);
  }

  // Test handling of null node (should not throw NPE based on source code)
  // getCost calls estimator.add(root) where root could be null. In CodeGenerator.add,
  // if node is null, it may throw NPE. We'll test that it does throw.
  @Test(expected = NullPointerException.class)
  public void testGetCost_nullRoot_throwsNullPointerException() {
    InlineCostEstimator.getCost(null);
  }

  // Test that continueProcessing stops when max cost reached
  @Test
  public void testGetCost_continueProcessing_falseAfterThreshold() {
    Node root = parse("function f() { return 1; }");
    // Cost without threshold is 22. Let's set threshold 10.
    int cost = InlineCostEstimator.getCost(root, 10);
    // Should stop early, cost >= 10.
    assertTrue(cost >= 10);
    // But not the full cost
    assertFalse(cost == 22);
  }

  // Test for a nested block structure
  @Test
  public void testGetCost_nestedBlock_returnsCorrectCost() {
    Node root = parse("{ a; { b; c; } }");
    int cost = InlineCostEstimator.getCost(root);
    // The code generator will produce: "ab;ab;ab;" -> but whitespace is removed
    // Actually block braces generate "{" and "}" which are characters.
    // Let's just verify cost is positive and reasonable.
    assertTrue(cost > 0);
    // More precise: "{" (1) + "ab" (2) + ";" (1) + "{" (1) + "ab" (2) + ";" (1) + "ab" (2) + ";" (1) + "}" (1) + "}" (1) = 13
    assertEquals(13, cost);
  }

  // Test for a conditional expression
  @Test
  public void testGetCost_conditionalExpression_returnsCorrectCost() {
    Node root = parse("a ? b : c");
    int cost = InlineCostEstimator.getCost(root);
    // "ab" + "?" + " " + "ab" + " " + ":" + " " + "ab" = 2+1+1+2+1+1+1+2 = 11
    // But whitespace is removed: "ab?ab:ab" = 7
    assertEquals(7, cost);
  }

  // Test cost for an array literal
  @Test
  public void testGetCost_arrayLiteral_returnsCorrectCost() {
    Node root = parse("[1, 2, 3]");
    int cost = InlineCostEstimator.getCost(root);
    // "[1,2,3]" = 7 chars
    assertEquals(7, cost);
  }

  // Test cost for an object literal
  @Test
  public void testGetCost_objectLiteral_returnsCorrectCost() {
    Node root = parse("({a: 1})");
    int cost = InlineCostEstimator.getCost(root);
    // "({ab:1})" = 8 chars
    assertEquals(8, cost);
  }

  // Test that constant literals (true, false, null) are treated as free in the sense
  // that they are not shortened but the cost includes their actual characters.
  @Test
  public void testGetCost_constantLiteral_returnsActualCost() {
    Node root = parse("true");
    int cost = InlineCostEstimator.getCost(root);
    assertEquals(4, cost);
  }

  // Test edge case: threshold exactly matching a token boundary
  @Test
  public void testGetCost_thresholdExactMatch_stopsAfterThatToken() {
    Node root = parse("ab");
    int cost = InlineCostEstimator.getCost(root, 2);
    // "ab" identifier -> cost 2, after append cost=2 >= 2, stop
    assertEquals(2, cost);
  }
}